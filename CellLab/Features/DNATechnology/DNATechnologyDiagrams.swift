struct DTDiagramView: View {
    let sceneID: String
    let time: Double
    var body: some View {
        Canvas { context, size in
            guard let scene = DTScene.all[sceneID] else { return }
            let scale = min(size.width / 360, size.height / 240)
            context.translateBy(x: (size.width - 360 * scale) / 2, y: (size.height - 240 * scale) / 2)
            context.scaleBy(x: scale, y: scale)
            for mark in scene.marks {
                switch mark {
                case let .box(x,y,w,h,r,fill,stroke,width):
                    draw(Path(roundedRect: CGRect(x:x,y:y,width:w,height:h), cornerRadius:r), fill:fill, stroke:stroke, width:width, context:&context)
                case let .oval(x,y,w,h,fill,stroke,width):
                    draw(Path(ellipseIn: CGRect(x:x,y:y,width:w,height:h)), fill:fill, stroke:stroke, width:width, context:&context)
                case let .line(points,color,width):
                    guard let first = points.first else { continue }
                    var path = Path(); path.move(to: CGPoint(x:first.x,y:first.y))
                    for p in points.dropFirst() { path.addLine(to: CGPoint(x:p.x,y:p.y)) }
                    context.stroke(path, with:.color(Color(dtHex:color)), style:StrokeStyle(lineWidth:width,lineCap:.round,lineJoin:.round))
                case let .label(value,x,y,size,color,bold):
                    context.draw(Text(value).font(.system(size:size,weight:bold ? .semibold : .regular,design:.rounded)).foregroundStyle(Color(dtHex:color)), at:CGPoint(x:x,y:y))
                }
            }
            if scene.motion.count > 1 {
                let progress = time.truncatingRemainder(dividingBy:4) / 4 * Double(scene.motion.count-1)
                let index = min(scene.motion.count-2,Int(progress))
                let a=scene.motion[index], b=scene.motion[index+1], q=progress-Double(index)
                let point=CGPoint(x:a.x+(b.x-a.x)*q,y:a.y+(b.y-a.y)*q)
                let pip=Path(ellipseIn:CGRect(x:point.x-3.5,y:point.y-3.5,width:7,height:7))
                context.fill(pip,with:.color(DTPalette.teal))
            }
        }
        .accessibilityHidden(true)
    }
    private func draw(_ path:Path,fill:UInt32?,stroke:UInt32?,width:Double,context:inout GraphicsContext) {
        if let fill { context.fill(path,with:.color(Color(dtHex:fill))) }
        if let stroke { context.stroke(path,with:.color(Color(dtHex:stroke)),lineWidth:width) }
    }
}
